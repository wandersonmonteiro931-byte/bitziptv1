// ── PUSH NOTIFICATION HANDLER ──
self.addEventListener("push", function (event) {
  event.waitUntil(
    (function () {
      var title = "Bitz IPTV";
      var body = "Nova notificação";
      var icon = "/logo-bitz.jpg";
      var badge = "/logo-bitz.jpg";
      var url = "/";

      if (event.data) {
        try {
          var rawText = event.data.text();
          if (rawText) {
            try {
              var data = JSON.parse(rawText);
              title = data.title || title;
              body = data.body || data.message || body;
              icon = data.icon || icon;
              badge = data.badge || badge;
              if (data.data && data.data.url) url = data.data.url;
            } catch (e) {
              body = rawText;
            }
          }
        } catch (e) {
          // stream unavailable
        }
      }

      return self.registration.showNotification(title, {
        body: body,
        icon: icon,
        badge: badge,
        vibrate: [200, 100, 200],
        tag: "bitz-" + Date.now(),
        renotify: true,
        requireInteraction: true,
        data: { url: url }
      });
    })()
  );
});

// ── NOTIFICATION CLICK HANDLER ──
self.addEventListener("notificationclick", function (event) {
  event.notification.close();
  var url = (event.notification.data && event.notification.data.url) || "/";
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then(function (windowClients) {
      for (var i = 0; i < windowClients.length; i++) {
        var client = windowClients[i];
        if (client.url.indexOf(self.location.origin) !== -1 && "focus" in client) {
          client.navigate(url);
          return client.focus();
        }
      }
      return self.clients.openWindow(url);
    })
  );
});

// ── SKIP WAITING (for PWA update prompt) ──
self.addEventListener("message", function (event) {
  if (event.data && event.data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});

// ── ACTIVATE: claim clients immediately ──
self.addEventListener("activate", function (event) {
  event.waitUntil(self.clients.claim());
});

// ── IMPORT WORKBOX SW (generated by vite-plugin-pwa) ──
// This loads precaching, routing, navigation fallback etc.
try {
  importScripts("./sw.js");
} catch (e) {
  console.warn("[SW] Could not load workbox sw.js:", e);
}
